"""Rebuild the continental public-camera reference; never reads phone data."""
import argparse, collections, csv, gzip, hashlib, io, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
SOURCE_URL = 'https://static.data.gouv.fr/resources/liste-des-radars-fixes-en-france/20251230-134204/jeu-de-donnees-liste-des-radars-fixes-en-france-12-2025.csv'
BOUNDARY_URL = 'https://etalab-datasets.geo.data.gouv.fr/contours-administratifs/2023/geojson/departements-5m.geojson.gz'

def inside(x, y, ring):
    result = False
    x1, y1 = ring[-1][:2]
    for point in ring:
        x2, y2 = point[:2]
        if (y1 > y) != (y2 > y) and x < (x2-x1)*(y-y1)/(y2-y1)+x1:
            result = not result
        x1, y1 = x2, y2
    return result

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--boundaries',type=Path,required=True);args=parser.parse_args()
    raw=(ROOT/'data/catalogue/ministere-20251230.csv').read_bytes()
    features=json.loads(gzip.decompress(args.boundaries.read_bytes()))['features']
    polygons=[];names={}
    for f in features:
        code=f['properties']['code']; names[code]=f['properties']['nom']
        coords=f['geometry']['coordinates']; groups=coords if f['geometry']['type']=='MultiPolygon' else [coords]
        for rings in groups:
            points=rings[0]
            bounds=(min(p[0] for p in points),min(p[1] for p in points),max(p[0] for p in points),max(p[1] for p in points))
            polygons.append((code,bounds,rings))
    def locate(lon,lat):
        hits=set()
        for code,(x1,y1,x2,y2),rings in polygons:
            if x1<=lon<=x2 and y1<=lat<=y2 and inside(lon,lat,rings[0]) and not any(inside(lon,lat,r) for r in rings[1:]): hits.add(code)
        if len(hits)>1: raise ValueError('Ambiguous department')
        return next(iter(hits),None)
    continental={c for c in names if len(c)==2 and c.isdigit() and 1<=int(c)<=95 and c!='20'}
    assert len(continental)==94
    labels={'ETF':'Radar fixe','ETD':'Vitesse discriminante','ETT':'Radar tourelle','ETU':'Radar urbain','ETVM':'Radar tronçon','ETFR':'Feu rouge','ETPN':'Passage à niveau'}
    items=[];excluded=collections.Counter();seen=set()
    for row in csv.DictReader(io.StringIO(raw.decode('cp1252')),delimiter=';'):
        lat=float(row['Latitude'].strip().replace(',','.'));lon=float(row[' Longitude'].strip().replace(',','.'))
        dept=locate(lon,lat)
        # Published points 8997/8999 sit close to the detailed Menton border.
        # Retain their source coordinates; only the administrative grouping is approximate.
        border_group = dept is None and row['Numéro de radar'].strip() in {'8997','8999'} and lat == 43.783 and lon in {7.5157,7.5162}
        if border_group: dept = '06'
        if dept not in continental:
            excluded[dept or 'unmatched']+=1
            if dept is None: print('UNMATCHED', row, flush=True)
            continue
        ident=row['Numéro de radar'].strip();category=row['Type de radar'].strip()
        assert ident not in seen;seen.add(ident)
        speed_text=row['VMA '].strip();speed=int(speed_text) if speed_text.isdigit() and 1<=int(speed_text)<=130 else None
        label=f'{dept} · {labels.get(category,category)} · '+(f'{speed} km/h' if speed else 'VMA non renseignée')+f' · MI-{ident}'
        items.append({'id':'mi:'+ident,'department':dept,'department_name':names[dept],'label':label,'category_code':category,
            'latitude':lat,'longitude':lon,'speed_limit_from_source_kmh':speed,'armed':False,'review_status':'reference_source',
            'source':{'name':'Ministere_interieur','record_id':ident,'snapshot_at':'2025-12-30T13:42:47.222000+00:00','url':SOURCE_URL},
            'department_assignment': 'near_border_approximation' if border_group else 'polygon',
            'source_record_sha256':hashlib.sha256(json.dumps(row,sort_keys=True,ensure_ascii=False).encode()).hexdigest()})
    items.sort(key=lambda x:(x['department'],x['id']))
    output={'format':'location-catalogue-preparation','version':1,'activation':'disabled','coordinate_system':'WGS84/EPSG:4326','scope':'France continentale, hors Corse et outre-mer','source_snapshot':'2025-12-30','items':items}
    path=ROOT/'assets/catalogue/catalogue_reference.json';path.write_text(json.dumps(output,ensure_ascii=False,indent=2)+'\n')
    dart='// Generated by tool/catalogue/build_france.py from public department boundaries.\nconst departmentNames = <String, String>{\n'
    dart+=''.join('  '+json.dumps(c)+': '+json.dumps(names[c],ensure_ascii=False)+',\n' for c in sorted(continental))+'};\n'
    (ROOT/'lib/models/department_names.dart').write_text(dart)
    summary={'source_url':SOURCE_URL,'source_sha256':hashlib.sha256(raw).hexdigest(),'boundary_url':BOUNDARY_URL,
        'boundary_sha256':hashlib.sha256(args.boundaries.read_bytes()).hexdigest(),'input_rows':len(items)+sum(excluded.values()),'output_rows':len(items),
        'departments':dict(sorted(collections.Counter(x['department'] for x in items).items())),'excluded':dict(excluded)}
    (ROOT/'data/catalogue/provenance.json').write_text(json.dumps(summary,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps(summary,ensure_ascii=False))
if __name__=='__main__': main()
